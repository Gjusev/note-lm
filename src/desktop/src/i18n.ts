// --- runtime ----------------------------------------------------------------
const DICT: Record<Lang, typeof de> = { de, en, es };

function readStored(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === "en" || v === "es" ? v : "de";
  } catch {
    return "de"; // storage blocked: German for this session
  }
}

let current: Lang = readStored();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

/** Switch language: persists, updates <html lang>, and re-renders subscribers. */
export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* storage blocked: session-only */
  }
  document.documentElement.lang = next;
  for (const fn of listeners) fn();
}

export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Lang as a React subscription — call once in App; t() reads module state. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribeLang, getLang);
}

/** Translate `key` with {var} interpolation; falls back to German, then to
 *  the key itself (a visible key beats a crash). */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICT[current] as Record<string, string>;
  const raw = dict[key] ?? (de as Record<string, string>)[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
    vars[name] != null ? String(vars[name]) : m
  );
}

// --- locale-aware formatting for .meta timestamps/sizes ---------------------
export function fmtDate(ts: number | string | Date): string {
  return new Date(ts).toLocaleDateString(LOCALE[current]);
}

export function fmtDateTime(ts: number | string | Date): string {
  return new Date(ts).toLocaleString(LOCALE[current]);
}

/** Megabytes with the locale's digit grouping (e.g. de "1.024 MB", en "1,024 MB"). */
export function fmtMB(bytes: number): string {
  return `${new Intl.NumberFormat(LOCALE[current]).format(Math.round(bytes / 1048576))} MB`;
}

/** Shared language picker (Settings top + onboarding welcome step). Built
 *  with createElement so i18n stays a .ts module. */
export function LangSelect({ style }: { style?: React.CSSProperties } = {}) {
  const lang = useLang();
  return createElement(
    "label",
    {
      className: "mono",
      style: { display: "flex", gap: "var(--space-1)", alignItems: "center", fontSize: "0.72rem", ...style },
    },
    t("lang.label"),
    createElement(
      "select",
      {
        value: lang,
        onChange: (e: React.ChangeEvent<HTMLSelectElement>) => setLang(e.target.value as Lang),
        "aria-label": t("lang.aria"),
        style: { width: "auto", padding: "0 var(--space-2)" },
      },
      LANGS.map((l) => createElement("option", { key: l.id, value: l.id }, l.label))
    )
  );
}
